// Generates src/airports.js from the OurAirports public-domain dataset.
// Usage:
//   curl -sL https://davidmegginson.github.io/ourairports-data/airports.csv -o <tmp>/airports.csv
//   node scripts/build-airports.js <tmp>/airports.csv
// Keeps every large/medium/small airport worldwide that has an IATA code.
// Tiers drive map styling: 1 = large, 2 = medium, 3 = small/GA.
const fs = require('fs');
const path = require('path');

const csvPath = process.argv[2];
if (!csvPath) { console.error('usage: node scripts/build-airports.js <airports.csv>'); process.exit(1); }

function parseCsvLine(line) {
  const out = [];
  let cur = '', inQ = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (inQ) {
      if (ch === '"') { if (line[i + 1] === '"') { cur += '"'; i++; } else inQ = false; }
      else cur += ch;
    } else if (ch === '"') inQ = true;
    else if (ch === ',') { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

const lines = fs.readFileSync(csvPath, 'utf8').split('\n');
const header = parseCsvLine(lines[0]);
const col = Object.fromEntries(header.map((h, i) => [h, i]));
const TYPES = { large_airport: 1, medium_airport: 2, small_airport: 3 };

const seen = new Set();
const rows = [];
for (let i = 1; i < lines.length; i++) {
  if (!lines[i].trim()) continue;
  const f = parseCsvLine(lines[i]);
  const tier = TYPES[f[col.type]];
  const iata = (f[col.iata_code] || '').trim().toUpperCase();
  if (!tier || !/^[A-Z0-9]{3}$/.test(iata) || seen.has(iata)) continue;
  const lat = +(+f[col.latitude_deg]).toFixed(3);
  const lon = +(+f[col.longitude_deg]).toFixed(3);
  if (!isFinite(lat) || !isFinite(lon)) continue;
  seen.add(iata);
  const fullName = f[col.name];
  const scheduled = (f[col.scheduled_service] || '').trim() === 'yes';
  // Category: m = military, i = international, r = regional (scheduled/medium),
  // p = private/GA. Military and international are detected from the name;
  // OurAirports has no explicit flags for either.
  // Military fields are excluded from the marketplace entirely.
  if (/\b(air ?force|afb|naval|navy|nas|marine|mcas|mcaf|army|aaf|air base|air station|airbase|joint base|raf|cfb|military)\b/i.test(fullName)) continue;
  // 'p' (private, PPR) is reserved for FAA private-use fields merged below —
  // everything from OurAirports with an IATA code is public use.
  const cat = (tier === 1 || /\b(international|intl)\b/i.test(fullName)) ? 'i' : 'r';
  const name = fullName.replace(/\s*(International|Regional)?\s*Airport$/i, (m, g1) => g1 ? ' ' + (g1[0] === 'I' ? 'Intl' : 'Rgnl') : '').trim().slice(0, 40);
  const city = (f[col.municipality] || '').trim().slice(0, 28);
  rows.push([iata, name, city, f[col.iso_country], lat, lon, tier, cat]);
}
// Merge FAA private-use (PPR) airports — built by scripts/build-private-airports.js
// from NASR data. These have FAA local identifiers (e.g. 07FA), not IATA codes.
const privPath = path.join(__dirname, '..', 'src', 'private-airports.json');
if (fs.existsSync(privPath)) {
  const priv = JSON.parse(fs.readFileSync(privPath, 'utf8'));
  // Spatial index so a PPR field that already exists under an IATA code (e.g.
  // Ocean Reef = OCA and 07FA) reclassifies the existing entry instead of
  // duplicating it at the same coordinates.
  const cellOf = (lat, lon) => Math.round(lat * 50) + ':' + Math.round(lon * 50);
  const byCell = new Map();
  rows.forEach((r) => {
    const k = cellOf(r[4], r[5]);
    (byCell.get(k) || byCell.set(k, []).get(k)).push(r);
  });
  let added = 0, reclassified = 0;
  for (const [lid, name, city, cc, lat, lon] of priv) {
    if (seen.has(lid)) continue; // FAA LID collides with an IATA code elsewhere
    let match = null;
    for (let dy = -1; dy <= 1 && !match; dy++) {
      for (let dx = -1; dx <= 1 && !match; dx++) {
        const cell = byCell.get(Math.round(lat * 50) + dy + ':' + (Math.round(lon * 50) + dx));
        if (cell) match = cell.find((r) => Math.abs(r[4] - lat) < 0.02 && Math.abs(r[5] - lon) < 0.02);
      }
    }
    if (match) {
      match[7] = 'p';
      reclassified++;
    } else {
      seen.add(lid);
      const row = [lid, name, city, cc, lat, lon, 3, 'p'];
      rows.push(row);
      const k = cellOf(lat, lon);
      (byCell.get(k) || byCell.set(k, []).get(k)).push(row);
      added++;
    }
  }
  console.log('merged', added, 'FAA private-use (PPR) airports;', reclassified, 'existing entries reclassified as private');
} else {
  console.warn('src/private-airports.json not found — private (PPR) airports omitted');
}

rows.sort((a, b) => a[6] - b[6] || (a[0] < b[0] ? -1 : 1));

const body = rows.map((r) => JSON.stringify(r)).join(',\n');
const out = '// GENERATED by scripts/build-airports.js from OurAirports (public domain) — do not edit by hand.\n'
  + '// [iata, name, city, country, lat, lon, tier, cat] tier 1 = large, 2 = medium, 3 = small/GA\n'
  + '// cat: i = international, r = regional, p = private/GA, m = military\n'
  + 'window.AIRPORTS = [\n' + body + '\n];\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'airports.js'), out);
const byCat = ['i', 'r', 'p', 'm'].map((c) => c + ':' + rows.filter((r) => r[7] === c).length);
console.log('wrote src/airports.js:', rows.length, 'airports (' + byCat.join(', ') + '),', Math.round(out.length / 1024) + ' KB');
